import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { CliError } from "../shared/errors.ts";
import type { Model } from "./expand.ts";
import { generatedPath, tildify, type Shell } from "./paths.ts";
import { GENERATED_HEADER, render } from "./shells/render.ts";

export type FileState = "missing" | "stale" | "current" | "foreign";

/** How the cached file for a shell compares with what we would write now. */
export const fileState = (model: Model, shell: Shell): FileState => {
  const file = generatedPath(shell);
  if (!existsSync(file)) return "missing";
  const current = readFileSync(file, "utf8");
  if (!current.startsWith(GENERATED_HEADER)) return "foreign";
  return current === render(model, shell) ? "current" : "stale";
};

/** Alias and function names defined in a generated file (empty if none). */
export const namesIn = (shell: Shell): Set<string> => {
  const file = generatedPath(shell);
  if (!existsSync(file)) return new Set();
  const text = readFileSync(file, "utf8");
  const found = [
    ...text.matchAll(/^alias ([^\s=]+)/gm),
    ...text.matchAll(/^([\w-]+)\(\) \{$/gm),
    ...text.matchAll(/^function (\S+)/gm),
  ].map((m) => m[1]);
  // `_aliaz_*` are completion helpers we emit, not user-visible names.
  return new Set(
    found.filter(
      (n): n is string => n !== undefined && !n.startsWith("_aliaz_"),
    ),
  );
};

/**
 * Writes the cached file for each shell. Only files we own (header present)
 * or that do not exist are written; anything else is refused, never replaced.
 */
export const generate = (
  model: Model,
  shells: Shell[],
  options: { dryRun?: boolean } = {},
): { shell: Shell; file: string; changed: boolean }[] =>
  shells.map((shell) => {
    const file = generatedPath(shell);
    const state = fileState(model, shell);
    if (state === "foreign") {
      throw new CliError(
        `${tildify(file)} was not generated by aliaz`,
        "Move it away; aliaz only overwrites its own files",
      );
    }
    const changed = state !== "current";
    if (changed && !options.dryRun) {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, render(model, shell));
    }
    return { shell, file, changed };
  });
