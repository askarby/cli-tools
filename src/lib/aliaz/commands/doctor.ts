import { existsSync } from "node:fs";
import type { Command } from "commander";
import { say } from "../../shared/ui.ts";
import { loadConfig } from "../config.ts";
import { materialize } from "../expand.ts";
import { loadSpec } from "../store.ts";
import { fileState } from "../generate.ts";
import { configPath, generatedPath, tildify } from "../paths.ts";
import { resolve } from "../resolve.ts";
import { checkLine, type Check } from "../ui.ts";

export const register = (program: Command): void => {
  program
    .command("doctor")
    .description("Check the config, the aliases and the generated files")
    .action(() => {
      const checks: Check[] = [];
      try {
        const config = loadConfig();
        checks.push(
          config.fromFile
            ? [true, `config: ${tildify(configPath())}`]
            : ["warn", "no config file; using defaults (run aliaz init)"],
        );
        if (!existsSync(config.aliasesFile)) {
          checks.push([
            "warn",
            `no aliases file yet: ${tildify(config.aliasesFile)}`,
          ]);
        }
        const model = materialize(loadSpec(config.aliasesFile));
        checks.push([true, `${model.rows.length} aliases parsed`]);
        for (const p of model.problems) {
          checks.push([p.level === "error" ? false : "warn", p.message]);
        }
        for (const r of resolve(model.rows)) {
          if (r.state === "broken") {
            checks.push([false, `${r.alias.name}: ${r.detail}`]);
          } else if (r.state === "shadowed") {
            checks.push(["warn", `${r.alias.name}: ${r.detail}`]);
          }
        }
        for (const shell of config.shells) {
          const where = tildify(generatedPath(shell));
          const state = fileState(model, shell);
          if (state === "current") checks.push([true, `${shell}: ${where}`]);
          else if (state === "foreign") {
            checks.push([
              false,
              `${shell}: ${where} is not generated by aliaz`,
            ]);
          } else {
            checks.push([
              "warn",
              `${shell}: ${where} is ${state}; run aliaz sync`,
            ]);
          }
        }
      } catch (error) {
        checks.push([false, (error as Error).message]);
      }
      for (const check of checks) say(checkLine(check));
      if (checks.some(([state]) => state === false)) process.exitCode = 1;
    });
};
